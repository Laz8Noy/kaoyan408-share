def html_table(headers, rows, tier_col=None, link_cols=()):
    th = "".join("<th>{}</th>".format(h) for h in headers)
    body = []
    for row in rows:
        tds = []
        for i, v in enumerate(row):
            cls = ""
            if tier_col is not None and i == tier_col - 1 and v in TIER_FILL:
                cls = ' class="tier tier-{}"'.format({"冲": "c", "稳": "w", "保": "b", "避坑": "x"}.get(v, ""))
            if i + 1 in link_cols and isinstance(v, str) and v.startswith("http"):
                tds.append('<td><a href="{}" target="_blank" rel="noopener">{}</a></td>'.format(v, row[0]))
            else:
                tds.append("<td{}>{}</td>".format(cls, v))
        body.append("<tr>{}</tr>".format("".join(tds)))
    return '<div class="tblwrap"><table><thead><tr>{}</tr></thead><tbody>{}</tbody></table></div>'.format(
        th, "".join(body))


